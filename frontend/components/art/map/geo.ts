/**
 * Corridor geography — India ⇄ UAE.
 *
 * Coastlines of the Arabian Sea basin digitised by hand in lon/lat
 * (degrees, WGS84) from known coastal places, accurate to roughly 0.1–0.2°
 * — finer than the dot pitch the map draws at. The mainland ring follows
 * the coast from the Gulf of Aden round Arabia, through Hormuz, along the
 * Gulf, out along Makran and round the Indian peninsula to Myanmar, then
 * closes along the edges of the data frame (lon 44–94, lat −8–36).
 *
 * Every port sits exactly on a vertex of the coastline.
 *
 * No borders are drawn — only land and water.
 */

